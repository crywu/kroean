for (const [category, rawList] of Object.entries(categoriesMap)) {
  for (const itemStr of rawList) {
    const [word, pos, meaning, sentence, sentenceMeaning] = itemStr.split('|');
    let conjKey = word;
    if (word === '쓰다') {
      conjKey = pos === 'verb' ? '쓰다(verb)' : '쓰다(adjective)';
    }

    const item = {
      id: vocabId++,
      word,
      pos,
      meaning,
      sentence,
      sentenceMeaning,
      category,
      status: 'learning',
      weight: 10
    };

    if ((pos === 'verb' || pos === 'adjective') && conjugationsMap[conjKey]) {
      item.conjugations = conjugationsMap[conjKey];
    }
    vocabData.push(item);
  }
}

